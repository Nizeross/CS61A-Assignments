def display(fruit, count):
    """在方括号中显示水果的数量和名称。

    >>> display('apples', 3)
    '[3 apples]'
    >>> display('apples', 1)
    '[1 apple]'
    >>> print(display('apples', 3) + display('kiwis', 3))
    [3 apples][3 kiwis]
    """
    assert count >= 1 and fruit[-1] == 's'
    if count == 1:
        fruit = fruit[:-1]  # 去掉复数词尾 s
    return '[' + str(count) + ' ' + fruit + ']'




